"""Write the on-chip memory images for the board from weights/mlp_64_int8.npz.

    python ml/gen_mem.py            # writes ml/mem/*.mem and ml/mem/model_params.svh

weights.mem   one 32-bit word per line (8 hex digits) = 4 int8 weights for one step k of one 4-output tile:
                  word[8*j +: 8] = W[k, 4*t + j]      j = 0..3  (byte 0 = lowest 8 bits = b_row[0])
              address = tile_base + t * K + k
                  layer 1: tile_base = 0,         K = 784, 16 tiles  -> 12,544 words
                  layer 2: tile_base = 12,544,    K = 64,   3 tiles  ->    192 words (outputs 10, 11 are zero padding)
              total depth 12,736 words (needs a 14-bit address)
bias1.mem     64 words, int32 bias per layer-1 output (hex, 8 digits)
bias2.mem     12 words, int32 bias per layer-2 output, last two are 0
model_params.svh   M1, SHIFT1, layer sizes and the base addresses as localparams

The script decodes its own files and checks that they rebuild W1_q, W2_q and the biases exactly.
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
NPZ = os.path.join(HERE, "weights", "mlp_64_int8.npz")
OUT = os.path.join(HERE, "mem")
N = 4


def pack_layer(W):
    """W is (K, n_out) int8. Returns a list of 32-bit words, tile by tile, step by step."""
    K, n_out = W.shape
    tiles = -(-n_out // N)
    Wp = np.zeros((K, tiles * N), dtype=np.int8)
    Wp[:, :n_out] = W
    words = []
    for t in range(tiles):
        for k in range(K):
            w = 0
            for j in range(N):
                w |= (int(Wp[k, t * N + j]) & 0xFF) << (8 * j)
            words.append(w)
    return words, tiles


def unpack_layer(words, K, n_out):
    tiles = -(-n_out // N)
    Wp = np.zeros((K, tiles * N), dtype=np.int8)
    for t in range(tiles):
        for k in range(K):
            w = words[t * K + k]
            for j in range(N):
                Wp[k, t * N + j] = np.array((w >> (8 * j)) & 0xFF, dtype=np.uint8).astype(np.int8)
    return Wp[:, :n_out]


def write_hex(path, values, digits):
    with open(path, "w") as f:
        f.write("\n".join(f"{v & ((1 << (4 * digits)) - 1):0{digits}x}" for v in values) + "\n")


def read_hex(path):
    with open(path) as f:
        return [int(line, 16) for line in f if line.strip()]


def main():
    q = np.load(NPZ)
    W1, W2 = q["W1_q"], q["W2_q"]
    b1, b2 = q["b1_q"].reshape(-1), q["b2_q"].reshape(-1)
    M1, shift1 = int(q["M1"]), int(q["shift1"])
    K1, n1 = W1.shape
    K2, n2 = W2.shape
    assert W1.dtype == np.int8 and W2.dtype == np.int8

    w1, t1 = pack_layer(W1)
    w2, t2 = pack_layer(W2)
    base2 = len(w1)
    depth = len(w1) + len(w2)
    b2_pad = list(b2) + [0] * (t2 * N - n2)
    assert len(b1) == n1 and n1 == t1 * N

    os.makedirs(OUT, exist_ok=True)
    write_hex(os.path.join(OUT, "weights.mem"), w1 + w2, 8)
    write_hex(os.path.join(OUT, "bias1.mem"), [int(v) for v in b1], 8)
    write_hex(os.path.join(OUT, "bias2.mem"), [int(v) for v in b2_pad], 8)
    with open(os.path.join(OUT, "model_params.svh"), "w") as f:
        f.write("// generated by ml/gen_mem.py - do not edit\n")
        f.write(f"localparam int L1_K = {K1};\nlocalparam int L1_TILES = {t1};\nlocalparam int L1_BASE = 0;\n")
        f.write(f"localparam int L2_K = {K2};\nlocalparam int L2_TILES = {t2};\nlocalparam int L2_BASE = {base2};\n")
        f.write(f"localparam int ROM_DEPTH = {depth};\n")
        f.write(f"localparam logic [15:0] L1_M = 16'd{M1};\nlocalparam int L1_SHIFT = {shift1};\n")

    # self-check: decode the files and compare with the npz
    words = read_hex(os.path.join(OUT, "weights.mem"))
    assert len(words) == depth
    assert np.array_equal(unpack_layer(words[:base2], K1, n1), W1), "W1 round trip failed"
    assert np.array_equal(unpack_layer(words[base2:], K2, n2), W2), "W2 round trip failed"
    rb1 = np.array([v - (1 << 32) if v >= 1 << 31 else v for v in read_hex(os.path.join(OUT, "bias1.mem"))])
    assert np.array_equal(rb1, b1), "bias1 round trip failed"
    print(f"weights.mem: {depth} words x 32 bit ({depth * 4 / 1024:.1f} KB), layer 2 starts at address {base2}")
    print(f"bias1.mem: {len(b1)} words, bias2.mem: {len(b2_pad)} words, M1 = {M1}, shift1 = {shift1}")
    print("round trip OK")


if __name__ == "__main__":
    main()